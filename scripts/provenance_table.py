"""Generate docs/provenance.md from the provenance registry."""
from pathlib import Path

import bolzakit  # noqa: F401  (populates the registry)
from bolzakit.provenance import registry


def main():
    rows = sorted(registry().items(), key=lambda kv: (kv[0].rsplit(".", 1)[0], kv[0]))
    out = ["# Provenance table", "", "Generated by `scripts/provenance_table.py`; do not edit.", "",
           "| function | label | source | error |", "|---|---|---|---|"]
    for name, i in rows:
        esc = lambda s: (s or "").replace("|", "\\|").replace("\n", " ")
        out.append(f"| `{name}` | {i.label} | {esc(i.source)} | {esc(i.error)} |")
    path = Path(__file__).resolve().parent.parent / "docs" / "provenance.md"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {path} ({len(rows)} entries)")


if __name__ == "__main__":
    main()
